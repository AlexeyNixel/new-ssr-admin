/**
 * Теги размещения новости на главной странице сайта.
 *
 * Это не тематические теги, а переключатель блока, в который попадёт новость.
 * Логика размещения живёт во фронте: frontend/app/utils/postTags.ts (getPostKind):
 *  - «Партнёр»               → не попадает в «Анонсы и события», уходит в «Информацию партнёров»;
 *  - «Актуальное», «События» → правая колонка блока «Анонсы и события»;
 *  - «Анонсы»                → центральная колонка.
 * Поэтому у новости должен быть ровно один такой тег: при двух сразу новость
 * молча уедет в колонку с более высоким приоритетом.
 *
 * id совпадают с фронтом; title — запасной вариант, если в локальной базе другие id.
 */
export interface PlacementTag {
  id: string;
  title: string;
  /** Куда попадёт новость — подсказка для редактора */
  hint: string;
  /** Правило выбора для модели */
  rule: string;
}

