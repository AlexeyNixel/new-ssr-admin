/**
 * Режимы ИИ-обработки текста новостей и промпты для модели.
 *
 * Используется и на сервере (server/api/ai/format.post.ts строит запрос к
 * модели), и в клиенте (кнопка ИИ в редакторе показывает список режимов).
 * Поэтому модуль не должен тянуть серверных зависимостей.
 *
 * Модель на ai.infomania.ru — небольшая (qwen3:1.7b), поэтому промпты:
 *  - жёстко ограничивают набор HTML-тегов (иначе ломает разметку редактора);
 *  - запрещают выдумывать факты (главное требование для новостей);
 *  - требуют вернуть ТОЛЬКО результат, без пояснений и markdown-ограждений.
 */

export type AiModeId = 'proofread' | 'format' | 'rewrite' | 'announce';

/** Формат ответа: html — вставляется в редактор, text — копируется в описание. */
export type AiOutput = 'html' | 'text';

export interface AiMode {
  id: AiModeId;
  /** Подпись в интерфейсе */
  label: string;
  /** Короткое пояснение под подписью */
  description: string;
  /** Иконка lucide */
  icon: string;
  output: AiOutput;
  /** Системный промпт для модели */
  system: string;
  /** Температура: ниже — точнее и стабильнее */
  temperature: number;
}

